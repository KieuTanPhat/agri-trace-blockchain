describe("route access matrix", () => {
  it("keeps platform and role access per management route", () => {
    const matrix = Object.fromEntries(
      roles.map((role) => [
        role,
        routes.filter((path) => canAccessManagementRoute(path, role)).join(" "),
      ]),
    );
    const production = routes
      .filter((path) => canAccessManagementRoute(path, "DISTRIBUTOR", true))
      .join(" ");
    expect({
      ...matrix,
      DISTRIBUTOR_WITH_PRODUCTION: production,
    }).toMatchSnapshot();
  });
  it("keeps enterprise permission access per management route", () => {
    const matrix = Object.fromEntries(
      Object.entries(accesses).map(([name, access]) => [
        name,
        routes.filter((path) => canUseEnterpriseRoute(path, access)).join(" "),
      ]),
    );
    expect(matrix).toMatchSnapshot();
  });
});
